drop policy if exists "site-assets public read" on storage.objects;
create policy "site-assets public read" on storage.objects
  for select to anon, authenticated using (bucket_id = 'site-assets');

drop policy if exists "site-assets editors upload" on storage.objects;
create policy "site-assets editors upload" on storage.objects
  for insert to authenticated with check (bucket_id = 'site-assets' and public.is_editor());

