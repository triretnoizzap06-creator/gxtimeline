-- GX27 Operations — Supabase schema (final)
--
-- How to run: Supabase → SQL Editor → New query → paste this ENTIRE file → Run.
-- Safe to run multiple times: it only creates what doesn't exist yet and
-- replaces functions/policies. Existing data is NEVER deleted.
--
-- Data model
--   site_content      2 rows: 'draft' (being edited by admins) and 'published' (what visitors see)
--   content_versions  every draft save (append-only) → Version history & restore
--   site_admins       who may edit (editor) and publish (admin)
--   publish_log       history of save / publish / code deploys
--   storage: bucket 'site-assets' for logo uploads (public read)
--
-- Security
--   • All writes go through SECURITY DEFINER functions that check the role.
--   • Roles are read from auth.users by auth.uid() and the email must be
--     CONFIRMED — not from editable token claims.
--   • Visitors (anon) can only read the 'published' row.
--   • The app does not need the service_role key at all.
-- ═══════════════════════════════════════════════════════════════════════════

-- ───────────────────────── Tables ─────────────────────────
create table if not exists public.site_content (
  id             text primary key check (id in ('draft', 'published')),
  data           jsonb       not null,
  version        integer     not null default 1,
  source_version integer,                        -- published row: the draft version that went live
  updated_at     timestamptz not null default now(),
  updated_by     text
);

create table if not exists public.content_versions (
  version  integer primary key,
  data     jsonb       not null,
  saved_at timestamptz not null default now(),
  saved_by text
);

create table if not exists public.site_admins (
  email    text primary key check (email = lower(email) and position('@' in email) > 1),
  role     text not null check (role in ('admin', 'editor')),
  added_at timestamptz not null default now(),
  added_by text
);

create table if not exists public.publish_log (
  id         bigint generated by default as identity primary key,
  kind       text not null check (kind in ('save', 'content', 'deploy')),
  status     text not null check (status in ('Saved', 'Publishing', 'Published', 'Failed')),
  version    integer,
  message    text,
  actor      text,
  created_at timestamptz not null default now()
);
create index if not exists publish_log_created_at_idx on public.publish_log (created_at desc);

-- ───────────────────────── Role helpers ─────────────────────────
-- Logged-in user's email, only if already confirmed (magic link / Google).
create or replace function public.current_email() returns text
language sql stable security definer set search_path = public, auth as $$
  select lower(u.email)
    from auth.users u
   where u.id = auth.uid()
     and u.email_confirmed_at is not null
$$;

create or replace function public.my_role() returns text
language sql stable security definer set search_path = public as $$
  select a.role from public.site_admins a where a.email = public.current_email()
$$;

create or replace function public.is_editor() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(public.my_role() in ('admin', 'editor'), false)
$$;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(public.my_role() = 'admin', false)
$$;

-- ───────────────────────── Save draft (editor + admin) ─────────────────────────
-- p_base_version = the draft version being edited. If someone else saved in the meantime,
-- fails with 'conflict:<current version>' unless p_force = true.
-- Every save also goes into content_versions, so overwrites never lose data.
create or replace function public.save_draft(p_data jsonb, p_base_version integer, p_force boolean default false)
returns integer
language plpgsql security definer set search_path = public as $$
declare
  v_current integer;
  v_next    integer;
  v_email   text := public.current_email();
begin
  if not public.is_editor() then
    raise exception 'not_authorized';
  end if;
  if p_data is null
     or jsonb_typeof(p_data -> 'tasks') is distinct from 'array'
     or jsonb_typeof(p_data -> 'finance') is distinct from 'array' then
    raise exception 'invalid_data: tasks dan finance harus berupa array';
  end if;

  select version into v_current from public.site_content where id = 'draft' for update;

  if not found then
    v_next := coalesce((select max(version) from public.content_versions), 0) + 1;
    insert into public.site_content (id, data, version, updated_at, updated_by)
    values ('draft', p_data, v_next, now(), v_email);
  else
    if not coalesce(p_force, false) and v_current is distinct from p_base_version then
      raise exception 'conflict:%', v_current;
    end if;
    v_next := greatest(v_current, coalesce((select max(version) from public.content_versions), 0)) + 1;
    update public.site_content
       set data = p_data, version = v_next, updated_at = now(), updated_by = v_email
     where id = 'draft';
  end if;

  insert into public.content_versions (version, data, saved_by) values (v_next, p_data, v_email);
  insert into public.publish_log (kind, status, version, actor) values ('save', 'Saved', v_next, v_email);

  -- auto-save makes many small versions: keep the newest 300 (plus the one that is live) and 2000 log rows
  delete from public.content_versions
   where version <= v_next - 300
     and version is distinct from (select source_version from public.site_content where id = 'published');
  delete from public.publish_log
   where id < (select min(id) from (select id from public.publish_log order by id desc limit 2000) t);
  return v_next;
end;
$$;

-- ───────────────────────── Publish (admin only) ─────────────────────────
create or replace function public.publish_content(p_note text default null)
returns json
language plpgsql security definer set search_path = public as $$
declare
  d       public.site_content%rowtype;
  v_email text := public.current_email();
begin
  if not public.is_admin() then
    raise exception 'not_authorized: hanya admin yang bisa publish';
  end if;

  select * into d from public.site_content where id = 'draft';
  if not found then
    raise exception 'no_draft: simpan dulu sebelum publish';
  end if;

  insert into public.site_content (id, data, version, source_version, updated_at, updated_by)
  values ('published', d.data, 1, d.version, now(), v_email)
  on conflict (id) do update
     set data           = excluded.data,
         version        = public.site_content.version + 1,
         source_version = excluded.source_version,
         updated_at     = now(),
         updated_by     = excluded.updated_by;

  insert into public.publish_log (kind, status, version, message, actor)
  values ('content', 'Published', d.version, left(p_note, 500), v_email);

  return json_build_object('source_version', d.version, 'published_at', now(), 'published_by', v_email);
end;
$$;

-- Record failed publishes and code deploys from the admin panel.
create or replace function public.log_event(p_kind text, p_status text, p_version integer default null, p_message text default null)
returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.is_editor() then
    raise exception 'not_authorized';
  end if;
  if p_kind in ('content', 'deploy') and not public.is_admin() then
    raise exception 'not_authorized';
  end if;
  insert into public.publish_log (kind, status, version, message, actor)
  values (p_kind, p_status, p_version, left(p_message, 1000), public.current_email());
end;
$$;

-- ───────────────────────── Team (admin only) ─────────────────────────
create or replace function public.set_admin(p_email text, p_role text)
returns void
language plpgsql security definer set search_path = public as $$
declare
  v_email text := lower(trim(p_email));
begin
  if not public.is_admin() then raise exception 'not_authorized'; end if;
  if p_role not in ('admin', 'editor') then raise exception 'invalid_role'; end if;
  if v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'invalid_email'; end if;
  if v_email = public.current_email() then
    raise exception 'self_change: role akunmu sendiri tidak bisa diubah dari sini';
  end if;
  insert into public.site_admins (email, role, added_by) values (v_email, p_role, public.current_email())
  on conflict (email) do update set role = excluded.role;
end;
$$;

create or replace function public.remove_admin(p_email text)
returns void
language plpgsql security definer set search_path = public as $$
declare
  v_email text := lower(trim(p_email));
begin
  if not public.is_admin() then raise exception 'not_authorized'; end if;
  if v_email = public.current_email() then
    raise exception 'self_change: akunmu sendiri tidak bisa dihapus dari sini';
  end if;
  if v_email in (select email from public.site_admins where role = 'admin')
     and (select count(*) from public.site_admins where role = 'admin') <= 1 then
    raise exception 'last_admin: minimal harus ada satu admin';
  end if;
  delete from public.site_admins where email = v_email;
end;
$$;

-- ───────────────────────── Row Level Security ─────────────────────────
alter table public.site_content     enable row level security;
alter table public.content_versions enable row level security;
alter table public.site_admins      enable row level security;
alter table public.publish_log      enable row level security;

drop policy if exists "read published or editor" on public.site_content;
create policy "read published or editor" on public.site_content
  for select to anon, authenticated using (id = 'published' or public.is_editor());

drop policy if exists "editors read versions" on public.content_versions;
create policy "editors read versions" on public.content_versions
  for select to authenticated using (public.is_editor());

drop policy if exists "editors read team" on public.site_admins;
create policy "editors read team" on public.site_admins
  for select to authenticated using (public.is_editor());

drop policy if exists "editors read log" on public.publish_log;
create policy "editors read log" on public.publish_log
  for select to authenticated using (public.is_editor());

-- No insert/update/delete policies: tables can't be written directly from the browser.
-- Extra layer: revoke write privileges from the public roles.
revoke insert, update, delete, truncate on public.site_content, public.content_versions,
  public.site_admins, public.publish_log from anon, authenticated;
grant select on public.site_content, public.content_versions, public.site_admins, public.publish_log
  to anon, authenticated;

-- Functions: write functions only for logged-in users (the role is still checked inside).
revoke execute on function public.save_draft(jsonb, integer, boolean)      from public, anon;
revoke execute on function public.publish_content(text)                     from public, anon;
revoke execute on function public.log_event(text, text, integer, text)      from public, anon;
revoke execute on function public.set_admin(text, text)                     from public, anon;
revoke execute on function public.remove_admin(text)                        from public, anon;
grant  execute on function public.save_draft(jsonb, integer, boolean)       to authenticated;
grant  execute on function public.publish_content(text)                     to authenticated;
grant  execute on function public.log_event(text, text, integer, text)      to authenticated;
grant  execute on function public.set_admin(text, text)                     to authenticated;
grant  execute on function public.remove_admin(text)                        to authenticated;
grant  execute on function public.current_email(), public.my_role(), public.is_editor(), public.is_admin()
  to anon, authenticated;

